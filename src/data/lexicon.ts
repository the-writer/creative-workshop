// 排列数：从 n 个互异块中取 k 个有序排列
function perm(n: number, k: number): number {
  let r = 1;
  for (let i = 0; i < k; i += 1) r *= n - i;
  return r;
}

export function shortNameCount(race: RaceKey): number {
  const n = SYLLABLES[race].length;
  return perm(n, 2) + perm(n, 3);
}

export interface TypeCombinationInfo {
  person: number;
  place: number;
  office: number;
  nickname: number;
  total: number;
}

export function computeRaceCombinations(race: RaceKey): TypeCombinationInfo {
  const roots = LEXICON[race];
  const shortCount = shortNameCount(race);
  const placeVariants =
    roots.placePrefix2.length * roots.placeSuffix1.length +
    roots.placePrefix1.length * roots.placeSuffix1.length +
    roots.placePrefix2.length * roots.placeSuffix2.length +
    roots.placePrefix1.length * roots.placeSuffix2.length;

  // 绰号 2-8 字：2字=1词，3字=1词+补字，4字=2词，5字=2词+补字，6字=3词，7字=3词+补字，8字=4词
  const nickTwo = roots.nickProfession.length + roots.nickAppearance.length + roots.nickDeed.length + roots.nickTerrain.length + roots.nickContract.length;
  const nickThree = nickTwo * roots.nickSingles.length;
  const nickFour = nickTwo * nickTwo;
  const nickFive = nickFour * roots.nickSingles.length;
  const nickSix = nickTwo * nickTwo * nickTwo;
  const nickSeven = nickSix * roots.nickSingles.length;
  const nickEight = nickFour * nickFour;
  const nickTotal = nickTwo + nickThree + nickFour + nickFive + nickSix + nickSeven + nickEight;

  const personSuffixTotal =
    shortCount + placeVariants + roots.professions.length + roots.contractTitles.length + roots.bloodTitles.length + roots.titleWords.length;
  const person = shortCount * personSuffixTotal + nickTotal * shortCount;
  const place = placeVariants;
  const office = roots.officeTerritories.length * roots.officePowers.length * roots.officeLevels.length;
  const nickname = nickTotal;

  return { person, place, office, nickname, total: person + place + office + nickname };
}

export function computeCombinationTotals(): {
  perRace: Record<RaceKey, TypeCombinationInfo>;
  grandTotal: number;
  detail: Record<NameTypeKey, number>;
} {
  const human = computeRaceCombinations('human');
  const demon = computeRaceCombinations('demon');
  return {
    perRace: { human, demon },
    grandTotal: human.total + demon.total,
    detail: {
      person: human.person + demon.person,
      place: human.place + demon.place,
      office: human.office + demon.office,
      nickname: human.nickname + demon.nickname,
    },
  };
}

export function formatCombination(n: number): string {
  if (n >= 1000000000000) return `${Math.floor(n / 1000000000000)}万亿${Math.floor((n % 1000000000000) / 100000000)}亿`;
  if (n >= 100000000) return `${Math.floor(n / 100000000)}亿${Math.floor((n % 100000000) / 10000)}万`;
  if (n >= 10000) return `${Math.floor(n / 10000)}万${Math.floor((n % 10000) / 1000)}千`;
  return String(n);
}